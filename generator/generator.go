// Package generator derives SQL migration files from a [compiler.CompiledSchema].
//
// Given a sealed, compiled schema it produces an ordered [Plan] of [MigrationFile]
// values — one shared infrastructure file followed by one file per system entity
// in dependency-safe topological order. CustomDefinition entities are skipped
// because they share the custom_entity_records table.
//
// Usage:
//
//	plan, err := generator.Generate(schema, generator.Options{})
//	if err != nil { ... }
//	for _, f := range plan.Files {
//	    os.WriteFile(filepath.Join(dir, f.Name+".sql"), []byte(f.SQL), 0o644)
//	}
package generator

import (
	"fmt"
	"strings"

	"awo.so/awo/compiler"
	"awo.so/awo/def"
)

// Plan is the ordered list of migration files to be written.
// Files are ordered by entity dependency (topological order from Graph).
type Plan struct {
	Files []MigrationFile
}

// MigrationFile is a single named SQL migration file.
type MigrationFile struct {
	// Name is the filename without extension (e.g. "000001_finance_invoice").
	Name string
	// SQL is the full DDL content to write.
	SQL string
}

// Options configures the generator.
type Options struct {
	// MigrationDir is where .sql files will be written (default: "db/migrations").
	MigrationDir string
	// StartSeq is the starting sequence number for file naming (default: 1).
	StartSeq int
}

// Generate derives a migration Plan from a CompiledSchema.
// Files are ordered by the dependency graph topological order so that
// referenced tables exist before tables that FK into them.
// CustomDefinition entities are skipped (they use custom_entity_records).
func Generate(schema *compiler.CompiledSchema, opts Options) (*Plan, error) {
	if opts.StartSeq <= 0 {
		opts.StartSeq = 1
	}

	// Get topological order from graph if available.
	var orderedEntities []*compiler.EntitySchema
	if schema.Graph != nil && len(schema.Graph.TopologicalOrder) > 0 {
		for _, name := range schema.Graph.TopologicalOrder {
			es := schema.ByName[name]
			if es != nil && es.IsSystem {
				orderedEntities = append(orderedEntities, es)
			}
		}
		// Add any system entities not in the graph order (defensive).
		inOrder := make(map[string]bool, len(orderedEntities))
		for _, es := range orderedEntities {
			inOrder[es.QualifiedName] = true
		}
		for _, es := range schema.Entities {
			if es.IsSystem && !inOrder[es.QualifiedName] {
				orderedEntities = append(orderedEntities, es)
			}
		}
	} else {
		for _, es := range schema.Entities {
			if es.IsSystem {
				orderedEntities = append(orderedEntities, es)
			}
		}
	}

	plan := &Plan{}
	seq := opts.StartSeq

	// Emit shared infrastructure once at the top.
	plan.Files = append(plan.Files, MigrationFile{
		Name: fmt.Sprintf("%06d_awo_infrastructure", seq),
		SQL:  sharedInfraSQL(),
	})
	seq++

	for _, es := range orderedEntities {
		sql, err := generateEntitySQL(es)
		if err != nil {
			return nil, fmt.Errorf("generator: entity %q: %w", es.QualifiedName, err)
		}
		plan.Files = append(plan.Files, MigrationFile{
			Name: fmt.Sprintf("%06d_%s", seq, es.QualifiedName),
			SQL:  sql,
		})
		seq++
	}

	return plan, nil
}

// sharedInfraSQL returns the shared infrastructure SQL:
// - pg_trgm extension
// - current_tenant_id() and set_tenant_context() for tenant RLS
// - set_org_context(), current_org_id(), current_org_path() for org-scoped RLS
// - generic updated_at and audit_log trigger functions
func sharedInfraSQL() string {
	return strings.TrimSpace(`
-- AWO Framework: shared infrastructure
-- Generated by awo/generator. Do not edit manually.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- current_tenant_id() reads the connection-level tenant context set by set_tenant_context().
CREATE OR REPLACE FUNCTION current_tenant_id() RETURNS uuid AS $$
BEGIN
    RETURN current_setting('awo.tenant_id', true)::uuid;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql STABLE;

-- set_tenant_context(tenant_id) sets the connection-level tenant context for RLS.
CREATE OR REPLACE FUNCTION set_tenant_context(p_tenant_id uuid) RETURNS void AS $$
BEGIN
    PERFORM set_config('awo.tenant_id', p_tenant_id::text, true);
END;
$$ LANGUAGE plpgsql;

-- set_org_context(org_id) sets the connection-level organization context for RLS.
-- Call after set_tenant_context when org-scoped entities are accessed.
CREATE OR REPLACE FUNCTION set_org_context(p_org_id uuid) RETURNS void AS $$
BEGIN
    PERFORM set_config('awo.org_id', p_org_id::text, true);
END;
$$ LANGUAGE plpgsql;

-- current_org_id() reads the connection-level org context set by set_org_context().
CREATE OR REPLACE FUNCTION current_org_id() RETURNS uuid AS $$
BEGIN
    RETURN current_setting('awo.org_id', true)::uuid;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql STABLE;

-- current_org_path() returns the materialized path of the current organization context.
-- Used by ScopeOrganizationTree RLS policies. Path format: "/parent-id/self-id/".
CREATE OR REPLACE FUNCTION current_org_path() RETURNS text LANGUAGE sql STABLE AS $$
    SELECT path FROM platform_organization
    WHERE id = current_org_id()
$$;

-- awo_set_updated_at() is the trigger function used by all entity tables.
CREATE OR REPLACE FUNCTION awo_set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- awo_audit_log() is a stub trigger function for audit logging.
-- Replace with a real implementation that writes to the audit log table.
CREATE OR REPLACE FUNCTION awo_audit_log() RETURNS trigger AS $$
BEGIN
    -- TODO: write to audit_log table when AllowAudit is true.
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

`) + "\n"
}

// generateEntitySQL produces the full DDL for a single system entity table.
func generateEntitySQL(es *compiler.EntitySchema) (string, error) {
	var b strings.Builder

	fmt.Fprintf(&b, "-- Entity: %s\n", es.QualifiedName)
	if es.Description != "" {
		fmt.Fprintf(&b, "-- %s\n", es.Description)
	}
	fmt.Fprintf(&b, "-- Generated by awo/generator. Do not edit manually.\n\n")

	// CREATE TABLE
	fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", quoteIdent(es.QualifiedName))

	// Standard columns first.
	b.WriteString("    id          UUID        NOT NULL DEFAULT gen_random_uuid(),\n")
	// ScopeSystem entities have no tenant_id column — they are global / platform-level.
	if es.Scope != def.ScopeSystem {
		b.WriteString("    tenant_id   UUID        NOT NULL REFERENCES platform_tenant(id),\n")
	}
	b.WriteString("    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),\n")
	b.WriteString("    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),\n")
	b.WriteString("    deleted_at  TIMESTAMPTZ,\n")

	// Entity fields.
	for _, f := range es.Fields {
		colDef, err := columnDef(f)
		if err != nil {
			return "", fmt.Errorf("field %q: %w", f.Name, err)
		}
		if f.Description != "" {
			fmt.Fprintf(&b, "    %-30s -- %s\n", colDef+",", f.Description)
		} else {
			fmt.Fprintf(&b, "    %s,\n", colDef)
		}
	}

	// Primary key.
	b.WriteString("\n    CONSTRAINT ")
	b.WriteString(es.QualifiedName)
	b.WriteString("_pkey PRIMARY KEY (id)")

	// UNIQUE constraints.
	for _, f := range es.Fields {
		if f.Unique {
			fmt.Fprintf(&b, ",\n    CONSTRAINT %s_%s_uniq UNIQUE (%s)", es.QualifiedName, f.Name, quoteIdent(f.Name))
		}
	}

	// CHECK constraints for Select fields.
	for _, f := range es.Fields {
		if f.Type == def.FieldTypeSelect && len(f.Options) > 0 {
			quoted := make([]string, len(f.Options))
			for i, o := range f.Options {
				quoted[i] = "'" + strings.ReplaceAll(o, "'", "''") + "'"
			}
			fmt.Fprintf(&b, ",\n    CONSTRAINT %s_%s_check CHECK (%s IN (%s))",
				es.QualifiedName, f.Name, quoteIdent(f.Name), strings.Join(quoted, ", "))
		}
	}

	b.WriteString("\n);\n\n")

	// COMMENT on table.
	if es.Description != "" {
		fmt.Fprintf(&b, "COMMENT ON TABLE %s IS %s;\n\n", quoteIdent(es.QualifiedName), quoteLiteral(es.Description))
	}

	// RLS — only for tenant-scoped and org-scoped entities.
	if es.Scope != def.ScopeSystem {
		fmt.Fprintf(&b, "ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", quoteIdent(es.QualifiedName))
		fmt.Fprintf(&b, "ALTER TABLE %s FORCE ROW LEVEL SECURITY;\n\n", quoteIdent(es.QualifiedName))
		// Tenant isolation policy — applies to all non-system scopes.
		fmt.Fprintf(&b, "CREATE POLICY %s_tenant_isolation ON %s\n    USING (tenant_id = current_tenant_id());\n\n",
			es.QualifiedName, quoteIdent(es.QualifiedName))
		// Additional org isolation policy for organization-scoped entities.
		switch es.Scope {
		case def.ScopeOrganization:
			fmt.Fprintf(&b, "CREATE POLICY %s_org_isolation ON %s\n    USING (org_id = current_org_id());\n\n",
				es.QualifiedName, quoteIdent(es.QualifiedName))
		case def.ScopeOrganizationTree:
			// Tree policy: org must be the current org or a descendant.
			// Materialized path format is "/parent-id/.../self-id/"; subtree
			// members share a common path prefix with the current org's path.
			fmt.Fprintf(&b, "CREATE POLICY %s_org_tree_isolation ON %s\n    USING (org_id IN (\n        SELECT id FROM platform_organization\n        WHERE path LIKE current_org_path() || '%%'\n    ));\n\n",
				es.QualifiedName, quoteIdent(es.QualifiedName))
		}
	}

	// updated_at trigger.
	triggerName := es.QualifiedName + "_set_updated_at"
	fmt.Fprintf(&b, "CREATE TRIGGER %s\n    BEFORE UPDATE ON %s\n    FOR EACH ROW EXECUTE FUNCTION awo_set_updated_at();\n\n",
		triggerName, quoteIdent(es.QualifiedName))

	// Indexes.
	// Standard index on tenant_id (not needed for system-scoped entities).
	if es.Scope != def.ScopeSystem {
		fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_tenant_id_idx ON %s (tenant_id);\n",
			es.QualifiedName, quoteIdent(es.QualifiedName))
	}
	// Composite index on (tenant_id, org_id) for org-scoped entities.
	if es.Scope == def.ScopeOrganization || es.Scope == def.ScopeOrganizationTree {
		fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_tenant_org_id_idx ON %s (tenant_id, org_id);\n",
			es.QualifiedName, quoteIdent(es.QualifiedName))
	}

	// GIN trigram index for Searchable fields.
	for _, f := range es.Fields {
		if f.Searchable && (f.Type == def.FieldTypeData || f.Type == def.FieldTypeSmallText) {
			fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_%s_trgm_idx ON %s USING GIN (%s gin_trgm_ops);\n",
				es.QualifiedName, f.Name, quoteIdent(es.QualifiedName), quoteIdent(f.Name))
		}
	}

	// FK indexes for Link fields.
	for _, f := range es.Fields {
		if f.Type == def.FieldTypeLink {
			fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_%s_idx ON %s (%s);\n",
				es.QualifiedName, f.Name, quoteIdent(es.QualifiedName), quoteIdent(f.Name))
		}
	}

	// Audit trigger (when AllowAudit is true).
	if es.AllowAudit {
		auditTrigger := es.QualifiedName + "_audit"
		fmt.Fprintf(&b, "\n-- Audit trigger\nCREATE TRIGGER %s\n    AFTER INSERT OR UPDATE OR DELETE ON %s\n    FOR EACH ROW EXECUTE FUNCTION awo_audit_log();\n",
			auditTrigger, quoteIdent(es.QualifiedName))
	}

	b.WriteString("\n")
	return b.String(), nil
}

// columnDef returns the SQL column definition for a FieldDef.
func columnDef(f def.FieldDef) (string, error) {
	col := quoteIdent(f.Name) + " "
	notNull := ""
	if f.Required {
		notNull = " NOT NULL"
	}

	switch f.Type {
	case def.FieldTypeData:
		maxLen := f.MaxLen
		if maxLen <= 0 {
			maxLen = 255
		}
		col += fmt.Sprintf("VARCHAR(%d)%s", maxLen, notNull)
	case def.FieldTypeSmallText:
		maxLen := f.MaxLen
		if maxLen <= 0 {
			maxLen = 1024
		}
		col += fmt.Sprintf("VARCHAR(%d)%s", maxLen, notNull)
	case def.FieldTypeLongText:
		col += "TEXT" + notNull
	case def.FieldTypeInt:
		col += "BIGINT" + notNull
	case def.FieldTypeFloat:
		col += "DOUBLE PRECISION" + notNull
	case def.FieldTypeCurrency:
		col += "NUMERIC(20,4)" + notNull
	case def.FieldTypeBool:
		col += "BOOLEAN NOT NULL DEFAULT FALSE"
	case def.FieldTypeDate:
		col += "DATE" + notNull
	case def.FieldTypeDateTime:
		col += "TIMESTAMPTZ" + notNull
	case def.FieldTypeTime:
		col += "TIME" + notNull
	case def.FieldTypeSelect:
		col += "VARCHAR(100)" + notNull
	case def.FieldTypeMultiSelect:
		col += "TEXT[]" + notNull
	case def.FieldTypeNamingSeries:
		col += "VARCHAR(100)" + notNull
	case def.FieldTypeJSON:
		col += "JSONB" + notNull
	case def.FieldTypeLink:
		target := f.LinkTarget
		if target == "" {
			return "", fmt.Errorf("FieldTypeLink requires LinkTarget")
		}
		col += fmt.Sprintf("UUID%s REFERENCES %s(id)", notNull, quoteIdent(target))
	case def.FieldTypeLinkList:
		col += "UUID[]" + notNull
	case def.FieldTypeDynamicLink:
		// DynamicLink generates two columns: {name}_id and {name}_type.
		// The column def for the _id column; callers must add {name}_type separately.
		// For simplicity in single-column DDL generation, emit as UUID with a comment.
		col += "UUID" + notNull
	default:
		return "", fmt.Errorf("unknown FieldType %q", f.Type)
	}

	return col, nil
}

// quoteIdent wraps a PostgreSQL identifier in double-quotes.
func quoteIdent(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

// quoteLiteral wraps a string value in single-quotes for SQL literals.
func quoteLiteral(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
